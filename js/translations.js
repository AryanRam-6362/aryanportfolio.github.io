// Global Translation Function
function applyTranslations(lang) {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            // Check if element has child HTML elements (like spans or strong tags)
            // If it is a simple tag, replace textContent.
            // If it has children, be careful not to overwrite styling tags.
            const hasHTML = el.querySelector('*');
            if (hasHTML) {
                // For tags with children, only translate their direct text node parts, 
                // or safely set innerHTML if the translation contains the tags.
                // We keep it safe by setting textContent for leaf items.
                // If it's a known multi-tag layout (like logo "ARYAN."), we handle it separately.
                if (key === "footer-precision") {
                    el.innerHTML = translations[lang][key];
                } else {
                    el.textContent = translations[lang][key];
                }
            } else {
                el.textContent = translations[lang][key];
            }
        }
    });

    // Save selected language
    localStorage.setItem('preferredLang', lang);
}

// Initialise language switch logic on page load
document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('preferredLang') || 'en';
    
    // Set active class on corresponding button and attach click events
    const langBtns = document.querySelectorAll('.lang-btn');
    langBtns.forEach(btn => {
        if (btn.getAttribute('data-lang') === savedLang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
        
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            const selectedLang = btn.getAttribute('data-lang');
            
            // Sync all selectors on the page (in case there are multiple, e.g. mobile vs desktop)
            document.querySelectorAll('.lang-btn').forEach(b => {
                if (b.getAttribute('data-lang') === selectedLang) {
                    b.classList.add('active');
                } else {
                    b.classList.remove('active');
                }
            });
            
            applyTranslations(selectedLang);
        });
    });

    applyTranslations(savedLang);
});
